#!/usr/bin/env bash
set -euo pipefail

mode=dry-run
ssh_source_ip=
ssh_user=${SUDO_USER:-}
for argument in "$@"; do
  case "$argument" in
    --dry-run) mode=dry-run ;;
    --apply) mode=apply ;;
    --ssh-source-ip=*) ssh_source_ip=${argument#*=} ;;
    --ssh-user=*) ssh_user=${argument#*=} ;;
    *) printf 'usage: %s [--dry-run|--apply] [--ssh-source-ip=CIDR] [--ssh-user=USER]\n' "$0" >&2; exit 64 ;;
  esac
done

cert_path=${STAGING_ORIGIN_CERT_PATH:-/srv/drlifeplus-staging/certs/cloudflare-origin.crt}
key_path=${STAGING_ORIGIN_KEY_PATH:-/srv/drlifeplus-staging/certs/cloudflare-origin.key}
real_ip_config=${STAGING_CLOUDFLARE_REAL_IP_CONFIG:-/srv/drlifeplus-staging/nginx/cloudflare-real-ip.conf}
sshd_dropin=/etc/ssh/sshd_config.d/00-drlifeplus-staging.conf
plan() { printf '[%s] %s\n' "$mode" "$*"; }

if [[ $mode == dry-run ]]; then
  plan "fetch Cloudflare ranges from https://www.cloudflare.com/ips-v4 and /ips-v6"
  plan "generate $real_ip_config with CF-Connecting-IP real-IP trust ranges"
  plan "allow Cloudflare ranges to TCP 80/443 through both UFW and Docker DOCKER-USER"
  plan "keep TCP 22 open, or restrict it to owner-provided source CIDR: ${ssh_source_ip:-all sources}"
  plan "check $cert_path and $key_path before writing firewall or sshd configuration"
  [[ -n $ssh_source_ip ]] && plan "restrict TCP 22 to owner-provided source CIDR: $ssh_source_ip"
  plan "write $sshd_dropin, validate sshd, enable fail2ban, and check mode-600 Origin files"
  exit 0
fi
if [[ $EUID -ne 0 ]]; then printf '%s\n' '--apply must run as root' >&2; exit 1; fi
if [[ -z $ssh_user || $ssh_user == root ]]; then
  printf '%s\n' '--apply requires --ssh-user=OWNER_LOGIN_USER (or sudo SUDO_USER); root is not accepted' >&2
  exit 1
fi
if ! getent passwd "$ssh_user" >/dev/null; then
  printf 'SSH user does not exist: %s\n' "$ssh_user" >&2
  exit 1
fi
ssh_home=$(getent passwd "$ssh_user" | awk -F: 'NR == 1 { print $6 }')
authorized_keys="$ssh_home/.ssh/authorized_keys"
if [[ ! -s $authorized_keys ]] || ! grep -Eq '^[[:space:]]*(ssh-|ecdsa-|sk-)' "$authorized_keys"; then
  printf 'no authorized SSH public key for %s; refusing to disable password login\n' "$ssh_user" >&2
  exit 1
fi
if [[ ! -f $cert_path || ! -f $key_path ]]; then printf '%s\n' 'Origin certificate and key must exist before --apply' >&2; exit 1; fi
cert_mode=$(stat -c '%a' "$cert_path" 2>/dev/null || stat -f '%Lp' "$cert_path")
key_mode=$(stat -c '%a' "$key_path" 2>/dev/null || stat -f '%Lp' "$key_path")
if [[ $cert_mode != 600 || $key_mode != 600 ]]; then printf '%s\n' 'Origin certificate and key must both have mode 600' >&2; exit 1; fi
tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT
curl --fail --silent --show-error --location https://www.cloudflare.com/ips-v4 > "$tmpdir/ips-v4"
curl --fail --silent --show-error --location https://www.cloudflare.com/ips-v6 > "$tmpdir/ips-v6"
if ! grep -Eq '^[0-9a-fA-F:.]+/[0-9]+$' "$tmpdir/ips-v4" || ! grep -Eq '^[0-9a-fA-F:.]+/[0-9]+$' "$tmpdir/ips-v6"; then
  printf '%s\n' 'Cloudflare IP range download was empty or malformed' >&2
  exit 1
fi
backup_dir=/var/backups/drlifeplus-staging-$(date +%Y%m%d%H%M%S)
install -d -m 700 "$backup_dir"
for ufw_file in /etc/ufw/after.rules /etc/ufw/after6.rules; do
  [[ -f $ufw_file ]] && cp -p "$ufw_file" "$backup_dir/"
done
printf 'UFW backup: %s\n' "$backup_dir" >&2
install -d -m 755 "$(dirname "$real_ip_config")"
{
  printf '%s\n' '# Generated by harden-server.sh from the current Cloudflare IP ranges.' 'real_ip_header CF-Connecting-IP;' 'real_ip_recursive on;'
  while IFS= read -r cidr; do printf 'set_real_ip_from %s;\n' "$cidr"; done < "$tmpdir/ips-v4"
  while IFS= read -r cidr; do printf 'set_real_ip_from %s;\n' "$cidr"; done < "$tmpdir/ips-v6"
} > "$tmpdir/cloudflare-real-ip.conf"
install -m 644 "$tmpdir/cloudflare-real-ip.conf" "$real_ip_config"
install -d -m 755 /etc/ssh/sshd_config.d
old_dropin="$tmpdir/old-dropin"
if [[ -f $sshd_dropin ]]; then cp -p "$sshd_dropin" "$old_dropin"; fi
restore_dropin() { if [[ -f $old_dropin ]]; then cp -p "$old_dropin" "$sshd_dropin"; else rm -f "$sshd_dropin"; fi; }
printf '%s\n' 'PasswordAuthentication no' 'PermitRootLogin no' 'KbdInteractiveAuthentication no' > "$sshd_dropin"
if ! sshd -t; then
  restore_dropin
  printf '%s\n' 'sshd -t failed; daemon was not restarted' >&2
  exit 1
fi
chmod 600 "$sshd_dropin"
sshd_effective=$(sshd -T -C "user=$ssh_user,host=localhost,addr=127.0.0.1")
for expected in 'passwordauthentication no' 'permitrootlogin no' 'kbdinteractiveauthentication no'; do
  grep -Fxq "$expected" <<< "$sshd_effective" || { restore_dropin; printf 'sshd effective config missing: %s\n' "$expected" >&2; exit 1; }
done
install_docker_user_rules() {
  local file=$1 ranges=$2 marker_begin='# BEGIN DRLIFE DOCKER-USER' marker_end='# END DRLIFE DOCKER-USER'
  local payload updated
  payload="$tmpdir/$(basename "$file").payload"
  updated="$tmpdir/$(basename "$file").updated"
  {
    printf '%s\n' "$marker_begin" '-A DOCKER-USER -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT'
    while IFS= read -r cidr; do printf '%s\n' "-A DOCKER-USER -p tcp -m multiport --dports 80,443 -s $cidr -j ACCEPT"; done < "$ranges"
    printf '%s\n' '-A DOCKER-USER -p tcp -m multiport --dports 80,443 -j DROP' '-A DOCKER-USER -j RETURN' "$marker_end"
  } > "$payload"
  [[ -f $file ]] || : > "$file"
  if grep -Fqx "$marker_begin" "$file"; then
    awk -v begin="$marker_begin" -v end="$marker_end" -v payload="$payload" '
      $0 == begin { skip=1; next }
      $0 == end { skip=0; while ((getline line < payload) > 0) print line; close(payload); next }
      !skip { print }
    ' "$file" > "$updated"
  else
    awk -v payload="$payload" '$0 == "COMMIT" { while ((getline line < payload) > 0) print line; close(payload) } { print }' "$file" > "$updated"
  fi
  install -m 644 "$updated" "$file"
}

apt-get update
apt-get install -y fail2ban ufw
ufw --force reset
ufw default deny incoming
ufw default allow outgoing
for ranges in "$tmpdir/ips-v4" "$tmpdir/ips-v6"; do
  while IFS= read -r cidr; do
    [[ -n $cidr ]] || continue
    ufw allow from "$cidr" to any port 80 proto tcp
    ufw allow from "$cidr" to any port 443 proto tcp
  done < "$ranges"
done
if [[ -n $ssh_source_ip ]]; then ufw allow from "$ssh_source_ip" to any port 22 proto tcp; else ufw allow 22/tcp; fi
install_docker_user_rules /etc/ufw/after.rules "$tmpdir/ips-v4"
install_docker_user_rules /etc/ufw/after6.rules "$tmpdir/ips-v6"
ufw --force enable
systemctl enable --now fail2ban
systemctl reload sshd 2>/dev/null || systemctl reload ssh
printf '%s\n' 'Applied. Verify a non-Cloudflare direct 80/443 connection is refused, then keep the current SSH connection open until a second key-only login succeeds.'
